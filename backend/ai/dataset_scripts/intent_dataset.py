def generate_dataset():
    intents = list(TEMPLATES.keys())
    target_total = 3000
    rows_per_intent = target_total // len(intents)

    rows = []
    row_id = 1

    for intent in sorted(intents):
        sub_dict = TEMPLATES[intent]
        sub_intents = sorted(sub_dict.keys())
        n_sub = len(sub_intents)
        rows_per_sub = rows_per_intent // n_sub
        remainder = rows_per_intent % n_sub

        for idx, sub_intent in enumerate(sub_intents):
            pool = sub_dict[sub_intent]
            quota = rows_per_sub + (1 if idx < remainder else 0)
            if len(pool) >= quota:
                chosen = random.sample(pool, quota)
            else:
                chosen = list(pool)
                while len(chosen) < quota:
                    needed = min(len(pool), quota - len(chosen))
                    chosen.extend(random.sample(pool, needed))
            for text in chosen:
                rows.append({"id": row_id, "text": text, "intent": intent, "sub_intent": sub_intent})
                row_id += 1

    random.shuffle(rows)
    for i, r in enumerate(rows, 1):
        r["id"] = i

    for path in OUTPUT_PATHS:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=["id", "text", "intent", "sub_intent"])
            writer.writeheader()
            writer.writerows(rows)
        print(f"DONE: {len(rows)} rows written to {path}")

    return len(rows), len(intents)


if __name__ == "__main__":
    n_rows, n_int = generate_dataset()
    print(f"Generated {n_rows} rows across {n_int} intents covering all 7 VoxaBank features.")
